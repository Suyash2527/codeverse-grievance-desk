/**
 * The triage vocabulary: chips, meters, time.
 *
 * Colour discipline, kept in one place so it cannot drift:
 *   teal  = the service and permitted automation
 *   amber = time pressure, nothing else
 *   rose  = a policy rule applies here, nothing else
 *
 * Every status chip carries a word as well as a colour. That is what makes
 * the teal/rose pair safe for colour-vision deficiency, where they sit close
 * together, and what makes the board readable at a glance across a room.
 */
"use client";

import { useLang } from "@/components/lang";
import type { AiLabelled, Sentiment } from "@/lib/api";

/** Every AI-produced value carries this mark. Rule 6, made visible. */
export function AiMark({ model }: { model?: string }) {
  return (
    <span
      className="inline-flex items-center gap-1.5 text-[11px] font-600 uppercase tracking-[0.06em] text-ink-3 bg-surface-sunk rounded-chip px-2 py-0.5 align-middle"
      title={
        model
          ? `Generated by ${model}. Not a verified fact.`
          : "Generated by the AI. Not a verified fact."
      }
    >
      <span className="w-1.5 h-1.5 rounded-chip bg-teal" aria-hidden />
      AI
    </span>
  );
}

/**
 * The policy verdict: the single most important fact on a case.
 *
 * Solid fill rather than a tinted outline, because this is the thing an
 * officer should see before they read anything else.
 */
export function VerdictChip({
  sensitive,
  outcome,
  animate = false,
  size = "md",
}: {
  sensitive: boolean;
  outcome?: string;
  animate?: boolean;
  size?: "md" | "lg";
}) {
  const { t } = useLang();
  const blocked = sensitive || outcome === "HUMAN_QUEUE";
  const tone = sensitive
    ? "bg-surface-card text-rose border-2 border-ink"
    : blocked
      ? "bg-amber text-white"
      : "bg-teal text-ink border-2 border-ink";
  const text = sensitive
    ? t("status.sensitive")
    : blocked
      ? t("status.review")
      : t("status.auto");
  const scale =
    size === "lg" ? "text-[15px] px-4 py-2" : "text-[13px] px-3 py-1.5";

  return (
    <span
      className={`${tone} ${scale} ${animate ? "chip-land" : ""} inline-flex items-center rounded-chip font-600 whitespace-nowrap`}
    >
      {text}
    </span>
  );
}

/** Priority. Loud where it matters, quiet where it does not. */
export function PriorityChip({ priority }: { priority: string }) {
  const { t } = useLang();
  const urgent = priority === "CRITICAL" || priority === "HIGH";
  const tone = urgent ? "bg-rose-tint text-rose border border-ink" : "bg-surface-sunk text-ink-2";
  return (
    <span
      className={`${tone} inline-flex items-center rounded-chip px-2.5 py-1 text-[12px] font-600 uppercase tracking-[0.04em]`}
    >
      {t(`priority.${priority}`)}
    </span>
  );
}

export function StatusText({ status }: { status: string }) {
  return <span className="text-[14px] text-ink-2">{status}</span>;
}

/**
 * Confidence against the configured threshold.
 *
 * The threshold tick stays on the bar: the number alone does not tell an
 * officer whether the system considered itself confident enough.
 */
export function ConfidenceMeter({
  confidence,
  threshold,
  animate = false,
}: {
  confidence: number;
  threshold: number;
  animate?: boolean;
}) {
  const { t } = useLang();
  const pct = Math.max(0, Math.min(1, confidence));
  const met = confidence >= threshold;
  return (
    <div className="w-full">
      <div className="flex items-baseline justify-between mb-2 gap-3">
        <span className="text-[13px] text-ink-3">{t("label.confidence")}</span>
        <span className="tabular text-[14px] text-ink font-600">
          {confidence.toFixed(2)}
          <span className="text-ink-3"> / {threshold.toFixed(2)}</span>
        </span>
      </div>
      <div className="relative h-3 bg-surface-sunk border-2 border-ink overflow-hidden rounded-chip">
        <div
          className={`${animate ? "meter-fill" : ""} h-full rounded-chip ${met ? "bg-teal" : "bg-amber"}`}
          style={{ width: `${pct * 100}%` }}
        />
        <div
          className="absolute top-0 h-full w-0.5 bg-ink-2"
          style={{ left: `${Math.min(1, threshold) * 100}%` }}
          aria-hidden
        />
      </div>
    </div>
  );
}

/**
 * Time remaining. Amber is the only colour that means time, and it appears
 * only once the case is actually close to its deadline.
 */
export function TimeLeft({
  hours,
  overdue,
  slaDays,
}: {
  hours: number | null;
  overdue: boolean;
  slaDays: number;
}) {
  const { t } = useLang();
  if (hours === null) return <span className="text-ink-3 text-[14px]">—</span>;

  const window = slaDays * 24;
  const pressing = hours < window * 0.25;
  const abs = Math.abs(hours);
  const label = abs < 48 ? `${abs.toFixed(0)}h` : `${(abs / 24).toFixed(0)}d`;

  if (overdue) {
    return (
      <span className="inline-flex items-center rounded-chip bg-amber text-white px-2.5 py-1 text-[13px] font-600 whitespace-nowrap">
        {label} {t("status.overdue")}
      </span>
    );
  }
  if (pressing) {
    return (
      <span className="inline-flex items-center rounded-chip bg-amber-tint text-ink border border-amber px-2.5 py-1 text-[13px] font-600 whitespace-nowrap">
        {label} {t("status.left")}
      </span>
    );
  }
  return (
    <span className="text-[14px] text-ink-2 tabular whitespace-nowrap">
      {label} {t("status.left")}
    </span>
  );
}

export function SentimentText({
  sentiment,
}: {
  sentiment: AiLabelled<Sentiment> | null;
}) {
  if (!sentiment) return null;
  return (
    <span className="text-[13px] text-ink-3 capitalize">
      {sentiment.value.sentiment.toLowerCase()}
    </span>
  );
}

/** Masked identity, shown as a withheld field rather than an absence. */
export function IdentityLine({
  name,
  masked,
}: {
  name: string | null;
  masked: boolean;
}) {
  const { t } = useLang();
  if (masked) {
    return (
      <span className="inline-flex items-center rounded-chip bg-rose-tint text-rose border border-ink px-2.5 py-0.5 text-[13px] font-500">
        Identity withheld
      </span>
    );
  }
  return <span className="text-[13px] text-ink-2">{name ?? t("status.notProvided")}</span>;
}

export function SectionRule({ label }: { label: string }) {
  return (
    <div className="mb-5">
      <h2 className="text-[20px] font-700 text-ink mb-3">
        <span className="accent">/ </span>
        {label}
      </h2>
      <div className="rule-hard" />
    </div>
  );
}

